// FE-D5 1 — allow plain http to a named list of hosts, in DEMO builds only.
//
// Why: a release build targets API 36, where Android blocks cleartext (http) by default, and the
// demo reaches local Supabase and the mock at the laptop's LAN address over http (FE-D4 4).
// Operator-approved, with conditions:
//
//   - One build-time variable, `DEMO_CLEARTEXT_HOSTS`: a comma-separated list of hosts. Unset or
//     empty -> this plugin changes NOTHING. It is deliberately not `EXPO_PUBLIC_`, so it is never
//     inlined into the app's JavaScript.
//   - Set -> http is allowed to exactly those hosts and nowhere else. The base config says
//     `cleartextTrafficPermitted="false"` explicitly, so every other host stays blocked.
//   - The release config guard (`src/api-target.ts`) is not touched: it governs the API address,
//     and a LAN address already passes it.
//
// CommonJS, because Expo's config loader `require`s plugins and `apps/field` is `"type": "module"`.
// `expo/config-plugins` ships inside the installed `expo` package: no new dependency.

/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS by necessity; see above. */
const fs = require('node:fs');
const path = require('node:path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const VARIABLE = 'DEMO_CLEARTEXT_HOSTS';
const RESOURCE = 'network_security_config';

/** A bare hostname or IPv4 address: no scheme, no port, no path, nothing XML could mistake. */
const HOST = /^[A-Za-z0-9](?:[A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$/u;

/**
 * The hosts in the variable, trimmed. Unset or empty is no hosts. Anything that is not a bare
 * host is refused LOUDLY: a build that silently dropped a mistyped host would be a demo that
 * cannot reach its server, found out on the phone.
 *
 * @param {string | undefined} value
 * @returns {string[]}
 */
const demoCleartextHosts = (value) => {
  const hosts = (value ?? '')
    .split(',')
    .map((host) => host.trim())
    .filter((host) => host !== '');
  for (const host of hosts) {
    if (!HOST.test(host)) {
      throw new Error(
        `${VARIABLE} must list bare hosts (e.g. 192.168.43.20), separated by commas. ` +
          `Refused "${host}": no scheme, no port, no path.`,
      );
    }
  }
  return hosts;
};

/**
 * The network security config: cleartext OFF for everything, ON for exactly these hosts.
 *
 * @param {readonly string[]} hosts
 * @returns {string}
 */
const networkSecurityConfigXml = (hosts) =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- Generated by apps/field/plugins/demo-cleartext.cjs from ${VARIABLE}. DEMO BUILDS ONLY. -->`,
    '<network-security-config>',
    '  <base-config cleartextTrafficPermitted="false" />',
    '  <domain-config cleartextTrafficPermitted="true">',
    ...hosts.map((host) => `    <domain includeSubdomains="false">${host}</domain>`),
    '  </domain-config>',
    '</network-security-config>',
    '',
  ].join('\n');

/**
 * The plugin. No hosts: the very same config back, untouched.
 *
 * @param {import('expo/config').ExpoConfig} config
 * @param {readonly string[]} hosts
 */
const withDemoCleartext = (config, hosts) => {
  if (hosts.length === 0) return config;

  const withResource = withDangerousMod(config, [
    'android',
    (modConfig) => {
      const dir = path.join(
        modConfig.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml',
      );
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${RESOURCE}.xml`), networkSecurityConfigXml(hosts));
      return modConfig;
    },
  ]);

  return withAndroidManifest(withResource, (modConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(modConfig.modResults);
    application.$['android:networkSecurityConfig'] = `@xml/${RESOURCE}`;
    return modConfig;
  });
};

module.exports = { VARIABLE, demoCleartextHosts, networkSecurityConfigXml, withDemoCleartext };
